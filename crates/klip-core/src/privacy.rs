pub fn has_sensitive_marker(formats: &[String]) -> bool {
    formats.iter().any(|f| {
        matches!(
            f.as_str(),
            "org.nspasteboard.ConcealedType"
                | "org.nspasteboard.TransientType"
                | "org.nspasteboard.AutoGeneratedType"
                | "ExcludeClipboardContentFromMonitorProcessing"
        )
    })
}

pub fn is_ignored_app(source_app: Option<&str>, ignored_apps: &[String]) -> bool {
    let Some(app) = source_app else {
        return false;
    };
    let lower = app.to_ascii_lowercase();
    ignored_apps.iter().any(|blocked| {
        let b = blocked.trim().to_ascii_lowercase();
        !b.is_empty() && (lower == b || lower.contains(&b))
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn filters_concealed_and_password_managers() {
        assert!(has_sensitive_marker(&[
            "public.utf8-plain-text".into(),
            "org.nspasteboard.ConcealedType".into()
        ]));
        assert!(has_sensitive_marker(&[
            "ExcludeClipboardContentFromMonitorProcessing".into()
        ]));
        assert!(!has_sensitive_marker(&["public.utf8-plain-text".into()]));

        let ignored = vec!["Bitwarden".into(), "1Password".into()];
        assert!(is_ignored_app(Some("Bitwarden"), &ignored));
        assert!(is_ignored_app(Some("1Password 8"), &ignored));
        assert!(!is_ignored_app(Some("Ghostty"), &ignored));
    }
}
